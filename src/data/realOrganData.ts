export function getRealOrganSpecimen(organId: string): RealOrganSpecimen {
  if (REAL_ORGAN_SPECIMENS[organId]) {
    return REAL_ORGAN_SPECIMENS[organId];
  }

  // Fallback for related organs
  if (organId.includes('lung')) return REAL_ORGAN_SPECIMENS['lung_right'];
  if (organId.includes('brain') || organId === 'cerebrum' || organId === 'cerebellum') return REAL_ORGAN_SPECIMENS['cerebrum'];
  if (organId.includes('intestine')) return REAL_ORGAN_SPECIMENS['large_intestine'];
  if (organId.includes('mouth') || organId.includes('tongue')) return REAL_ORGAN_SPECIMENS['larynx'];
  if (organId.includes('spine') || organId.includes('vertebrae') || organId.includes('skull')) return REAL_ORGAN_SPECIMENS['cranium'];

  return REAL_ORGAN_SPECIMENS['heart'];
}
